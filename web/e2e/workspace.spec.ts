import { expect, test } from '@playwright/test'

test('demo upload completes and results tabs work without external requests', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.route('**/*', (route) => {
    if (new URL(route.request().url()).hostname !== '127.0.0.1') {
      external.push(route.request().url())
      return route.abort()
    }
    return route.continue()
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const response = await page.goto('/')
  expect(response?.status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await page.getByRole('button', { name: 'Explore demo workspace' }).click()
  await expect(page.getByRole('heading', { name: 'From document to data.' })).toBeVisible()
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true })
  await page.getByLabel('Choose your file').setInputFiles({
    name: 'invoice.png',
    mimeType: 'image/png',
    buffer: Buffer.from('local demo file'),
  })
  await page.getByRole('button', { name: 'Upload & process' }).click()
  await expect(page.getByText('Processing', { exact: true })).toBeVisible()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible({ timeout: 15000 })
  await expect(page.getByRole('cell', { name: 'INV-2026-042', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Recognized text' }).click()
  await expect(page.getByText('NORTHSTAR STUDIO', { exact: false })).toBeVisible()
  await page.screenshot({ path: 'test-results/results-desktop.png', fullPage: true })
  const uploadedId = page.url().split('/jobs/')[1]!
  await page.getByRole('link', { name: 'Back to documents' }).click()
  const uploadedRow = page
    .getByRole('row')
    .filter({ has: page.getByRole('link', { name: `Open job ${uploadedId}` }) })
  await expect(uploadedRow).toBeVisible()
  await page.screenshot({ path: 'test-results/documents-desktop.png', fullPage: true })
  await uploadedRow.getByRole('button', { name: 'Delete document' }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.screenshot({ path: 'test-results/delete-dialog-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(uploadedRow).toBeVisible()
  await uploadedRow.getByRole('button', { name: 'Delete document' }).click()
  await page.getByRole('button', { name: 'Delete permanently' }).click()
  await expect(page.getByRole('alertdialog')).not.toBeVisible()
  await expect(page.getByRole('link', { name: `Open job ${uploadedId}` })).toHaveCount(0)
  await expect(page.getByText('Document deleted.', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Open job 01J8ZQJ9X7K3M4N5P6Q7R8S9TV' }).click()
  await page.getByRole('button', { name: 'Delete document' }).click()
  await page.getByRole('button', { name: 'Delete permanently' }).click()
  await expect(page.getByText('No documents yet', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  expect(errors).toEqual([])
  expect(external).toEqual([])
})

test('mobile workspace and sample result fit the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore demo workspace' }).click()
  await expect(page.getByRole('heading', { name: 'From document to data.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/workspace-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Toggle navigation' }).click()
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible()
  await page.getByRole('link', { name: /New document/ }).click()
  await page.getByRole('button', { name: 'View a sample result' }).click()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/results-mobile.png', fullPage: true })
  await page.getByRole('link', { name: 'Back to documents' }).click()
  await expect(page.getByRole('heading', { name: 'My documents' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/documents-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Delete document' }).click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toBeVisible()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/delete-dialog-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Delete permanently' }).click()
  await expect(page.getByText('No documents yet', { exact: true })).toBeVisible()
})
